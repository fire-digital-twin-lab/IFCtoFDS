"""Consumer contracts for queue persistence and worker execution."""

from typing import Any, Protocol


class JobStore(Protocol):
    @property
    def cache(self) -> dict[str, dict[str, Any]]: ...

    def get(self, jid: str) -> dict[str, Any] | None: ...
    def set(self, jid: str, job: dict[str, Any]) -> None: ...
    def delete(self, jid: str) -> None: ...
    def all_jobs(self) -> list[dict[str, Any]]: ...
    def items(self) -> Any: ...
    def count_pending(self) -> int: ...
    def snapshot(self, jid: str) -> dict[str, Any]: ...
    def read_result(self, jid: str) -> dict[str, Any]: ...


class WorkerProcesses(Protocol):
    def launch(self, directory: str) -> Any: ...
    def stop(self, process: Any) -> None: ...
    def rss(self, process: Any) -> int: ...


class JobRetention(Protocol):
    def cleanup_orphaned_directories(self, service: Any, max_age_s: int | None = None) -> None: ...
    def sweep(self, service: Any, now: float) -> None: ...
