"""Bounded local job queue using killable child processes and disk artifacts."""

import json
import os
from pathlib import Path
import subprocess
import sys
import threading
import time
import uuid
import psutil


class JobManager:
    def __init__(self, root=None, max_waiting=2, timeout_s=1800, retention_s=3600):
        self.root = Path(
            root or os.environ.get("IFCFDS_JOB_ROOT", str(Path.cwd() / ".jobs"))
        )
        self.root.mkdir(parents=True, exist_ok=True)
        self.max_waiting = max_waiting
        self.timeout_s = timeout_s
        self.retention_s = retention_s
        self.jobs = {}
        self.lock = threading.RLock()
        self.wake = threading.Event()
        self.closed = False
        self.thread = None

    def submit(self, paths, configuration, directory, mode="convert"):
        with self.lock:
            pending = sum(
                j["state"] in ("QUEUED", "RUNNING") for j in self.jobs.values()
            )
            if pending >= self.max_waiting + 1:
                raise OverflowError("Job queue is full")
            jid = uuid.uuid4().hex
            job = dict(
                id=jid,
                state="QUEUED",
                directory=str(directory),
                created=time.time(),
                error=None,
                process=None,
            )
            Path(directory, "request.json").write_text(
                json.dumps(
                    dict(
                        paths=[str(p) for p in paths],
                        configuration=configuration,
                        mode=mode,
                    )
                ),
                encoding="utf-8",
            )
            self.jobs[jid] = job
            if self.thread is None:
                self.thread = threading.Thread(target=self._loop, daemon=True)
                self.thread.start()
            self.wake.set()
            return self.snapshot(jid)

    def snapshot(self, jid):
        with self.lock:
            if jid not in self.jobs:
                raise KeyError(jid)
            return {
                k: v
                for k, v in self.jobs[jid].items()
                if k not in ("process", "directory")
            }

    def result(self, jid):
        with self.lock:
            job = self.jobs[jid]
            if job["state"] != "COMPLETED":
                raise ValueError("Job has no completed result")
            return json.loads(
                Path(job["directory"], "result.json").read_text(encoding="utf-8")
            )

    @staticmethod
    def _stop(process):
        if process and process.poll() is None:
            try:
                parent = psutil.Process(process.pid)
                for child in parent.children(recursive=True):
                    try:
                        child.kill()
                    except psutil.NoSuchProcess:
                        pass
                parent.kill()
                process.wait(timeout=10)
            except (psutil.NoSuchProcess, subprocess.TimeoutExpired):
                pass

    @staticmethod
    def _cleanup(job):
        # Job directories are generated by mkdtemp; only inputs and request need removal.
        directory = Path(job["directory"])
        for path in directory.glob("source-*.ifc"):
            path.unlink(missing_ok=True)
        (directory / "request.json").unlink(missing_ok=True)

    def cancel(self, jid):
        with self.lock:
            job = self.jobs[jid]
            if job["state"] in ("QUEUED", "RUNNING"):
                job["state"] = "CANCELLED"
                job["finished"] = time.time()
                self._stop(job["process"])
                self._cleanup(job)
            return self.snapshot(jid)

    def close(self):
        self.closed = True
        self.wake.set()
        for jid in list(self.jobs):
            self.cancel(jid)
        if self.thread:
            self.thread.join(timeout=5)

    def _loop(self):
        while not self.closed:
            with self.lock:
                for jid, job in list(self.jobs.items()):
                    if (
                        job.get("finished", time.time()) + self.retention_s
                        < time.time()
                    ):
                        directory = Path(job["directory"]).resolve()
                        if directory.parent == self.root.resolve():
                            import shutil

                            shutil.rmtree(directory)
                        del self.jobs[jid]
                running = next(
                    (j for j in self.jobs.values() if j["state"] == "RUNNING"), None
                )
                if running:
                    proc = running["process"]
                    if time.time() - running["started"] > self.timeout_s:
                        self._stop(proc)
                        running.update(
                            state="TIMED_OUT",
                            error="Job deadline exceeded",
                            finished=time.time(),
                        )
                        self._cleanup(running)
                    elif proc.poll() is not None:
                        directory = Path(running["directory"])
                        if (
                            proc.returncode == 0
                            and (directory / "result.json").exists()
                        ):
                            running.update(state="COMPLETED", finished=time.time())
                        else:
                            error = (
                                (directory / "error.txt").read_text(encoding="utf-8")
                                if (directory / "error.txt").exists()
                                else f"Worker exited {proc.returncode}"
                            )
                            running.update(
                                state="FAILED", error=error[:2000], finished=time.time()
                            )
                        self._cleanup(running)
                else:
                    queued = next(
                        (j for j in self.jobs.values() if j["state"] == "QUEUED"), None
                    )
                    if queued:
                        try:
                            proc = subprocess.Popen(
                                [
                                    sys.executable,
                                    "-m",
                                    "ifc_to_fds.jobs",
                                    queued["directory"],
                                ],
                                stdout=subprocess.DEVNULL,
                                stderr=subprocess.DEVNULL,
                                creationflags=getattr(
                                    subprocess, "CREATE_NO_WINDOW", 0
                                ),
                            )
                            queued.update(
                                state="RUNNING", started=time.time(), process=proc
                            )
                        except OSError as exc:
                            queued.update(
                                state="FAILED", error=str(exc), finished=time.time()
                            )
                            self._cleanup(queued)
            self.wake.wait(0.1)
            self.wake.clear()


def run_worker(directory):
    directory = Path(directory)
    try:
        from .pipeline import convert, save_artifacts

        request = json.loads((directory / "request.json").read_text(encoding="utf-8"))
        if request.get("mode") == "inventory":
            from .core.inventory import extract_inventory

            models = [extract_inventory(path)[0] for path in request["paths"]]
            result = dict(
                total_elements=sum(len(m.elements) for m in models),
                storeys=[s.name for m in models for s in m.storey_references],
                storey_references=[
                    s.model_dump() for m in models for s in m.storey_references
                ],
                sources=[m.source.model_dump() for m in models],
            )
        else:
            result = convert(request["paths"], request["configuration"])
            save_artifacts(result, directory / "model.fds")
        (directory / "result.json").write_text(json.dumps(result), encoding="utf-8")
        return 0
    except Exception as exc:
        (directory / "error.txt").write_text(
            f"{type(exc).__name__}: {exc}", encoding="utf-8"
        )
        return 1


if __name__ == "__main__":
    raise SystemExit(run_worker(sys.argv[1]))
