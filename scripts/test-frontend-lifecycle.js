const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const context = vm.createContext({console});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../frontend/src/shared/lifecycle.js'), 'utf8'), context);
const lifecycle = context.IfcFds.core.createLifecycle();
const target = new EventTarget();
let calls = 0, releases = 0;
lifecycle.listen(target, 'change', () => calls++);
lifecycle.own(() => releases++);
target.dispatchEvent(new Event('change'));
assert.equal(calls, 1);
lifecycle.destroy();
lifecycle.destroy();
target.dispatchEvent(new Event('change'));
assert.equal(calls, 1, 'Destroyed component retained an event listener');
assert.equal(releases, 1, 'Destroy must release each owned resource once');
lifecycle.own(() => releases++);
assert.equal(releases, 2, 'A late resource must be released after destruction');
console.log('Lifecycle removes listeners, releases resources once and rejects late ownership.');
